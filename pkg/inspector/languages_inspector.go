// Languages infers the list of languages used in a publication's (X)HTML
// documents through their guided navigation representation, and stores it as
// the "language" of the inferred accessibility object in OtherMetadata.
//
// The languages are ordered by the number of strings found in each of them,
// most used first. Languages with the same number of strings keep the order in
// which they were first encountered. A string is either:
//   - a guided navigation text, counted in its own language unless all of its
//     content is in other languages
//   - a run of text in another language inside of a text, which the HTML
//     converter expresses in the text's SSML with an xml:lang attribute
//
// Only declared languages are counted: text with no language in effect is
// ignored. Tags are normalized to their canonical BCP-47 form, and region or
// script subtags are kept, so "en" and "en-US" are two different languages.
//
// This inference is riskier than the others, so unlike them it is never merged
// into the publication's own metadata. The inspector always writes to the
// inferred accessibility object, and is only meant to be used when inferred
// accessibility metadata is split from the authored one.
type Languages struct {
	GuidedNavigationService pub.GuidedNavigationService

	counts     map[string]int // Number of strings for each language
	order      []string       // Languages, in the order they were first encountered
	uniqueDocs map[string]struct{}
}

// Name implements Inspector
func (n *Languages) Name() string {
	return "languages"
}

// InspectHREF implements Inspector
func (n *Languages) InspectHREF(href manifest.HREF) (*manifest.HREF, error) {
	// Identity
	return nil, nil
}

// InspectLink implements Inspector
func (n *Languages) InspectLink(link manifest.Link) (*manifest.Link, error) {
	if link.MediaType == nil || !link.MediaType.IsHTML() {
		return nil, nil
	}

	href := link.Href.String()
	if n.uniqueDocs == nil {
		n.uniqueDocs = make(map[string]struct{})
	}
	if _, ok := n.uniqueDocs[href]; ok {
		// Already counted this doc
		return nil, nil
	}
	n.uniqueDocs[href] = struct{}{}

	if !n.GuidedNavigationService.HasGuideForResource(href) {
		return nil, nil
	}

	doc, err := n.GuidedNavigationService.GuideForResource(context.TODO(), href)
	if err != nil {
		return nil, errors.Wrap(err, "failed loading guide for resource "+href)
	}
	n.count(doc.Guided)

	return nil, nil
}

// count adds the strings of the given objects and their descendants.
func (n *Languages) count(objs []guidednavigation.GuidedNavigationObject) {
	for i := range objs {
		text := objs[i].Text
		if text.Plain != "" || text.SSML != "" {
			inline, base := ssmlLanguages(text.SSML)
			if base {
				n.add(text.Language)
			}
			for _, lang := range inline {
				n.add(lang)
			}
		}
		n.count(objs[i].Children)
	}
}

// add counts one more string in the given language.
func (n *Languages) add(tag string) {
	lang := normalizeLanguage(tag)
	if lang == "" {
		return
	}
	if n.counts == nil {
		n.counts = make(map[string]int)
	}
	if _, ok := n.counts[lang]; !ok {
		n.order = append(n.order, lang)
	}
	n.counts[lang]++
}

// normalizeLanguage returns the canonical form of a BCP-47 language tag, or an
// empty string when there is nothing usable in it. A well-formed tag with a
// subtag that doesn't exist is still used, without that subtag.
func normalizeLanguage(tag string) string {
	tag = strings.TrimSpace(tag)
	if tag == "" {
		return ""
	}
	parsed, err := language.Parse(tag)
	if err != nil {
		var unknownSubtag language.ValueError
		if !stderrors.As(err, &unknownSubtag) {
			// Not well-formed
			return ""
		}
	}
	// The raw base language: Tag.Base would guess one when there is none
	if base, _, _ := parsed.Raw(); base.String() == "und" {
		// Undetermined, possibly with a region or script: no language to count
		return ""
	}
	return parsed.String()
}

const xmlNamespace = "http://www.w3.org/XML/1998/namespace"

// ssmlLanguages reads the SSML of a guided navigation text. It returns the
// language of each element that declares one with xml:lang, in document order,
// and whether any text is left in the language of the text itself.
//
// The markup is a fragment generated by the HTML converter. If it can't be
// read to the end, what was found until then is returned and the text counts
// as having content in its own language, same as a text with no SSML.
func ssmlLanguages(ssml string) (inline []string, base bool) {
	if ssml == "" {
		return nil, true
	}

	decoder := xml.NewDecoder(strings.NewReader(ssml))
	decoder.Strict = false // The fragment uses the readium: prefix without binding it

	// Whether each open element is in another language than the text's own
	var foreign []bool
	for {
		token, err := decoder.Token()
		if err == io.EOF {
			return inline, base
		} else if err != nil {
			return inline, true
		}

		switch t := token.(type) {
		case xml.StartElement:
			inForeign := len(foreign) > 0 && foreign[len(foreign)-1]
			for _, attr := range t.Attr {
				if attr.Name.Local == "lang" && (attr.Name.Space == xmlNamespace || attr.Name.Space == "xml") && attr.Value != "" {
					inline = append(inline, attr.Value)
					inForeign = true
					break
				}
			}
			foreign = append(foreign, inForeign)
		case xml.EndElement:
			if len(foreign) > 0 {
				foreign = foreign[:len(foreign)-1]
			}
		case xml.CharData:
			if (len(foreign) == 0 || !foreign[len(foreign)-1]) && strings.TrimSpace(string(t)) != "" {
				base = true
			}
		}
	}
}

// InspectManifest implements Inspector
func (n *Languages) InspectManifest(m manifest.Manifest) (*manifest.Manifest, error) {
	if len(n.order) == 0 {
		return nil, nil
	}

	// Most used first. The sort is stable, so ties keep their order of appearance
	languages := slices.Clone(n.order)
	slices.SortStableFunc(languages, func(a, b string) int {
		return cmp.Compare(n.counts[b], n.counts[a])
	})

	// Like the metadata's own language, a single one is written as a string
	if len(languages) == 1 {
		setInferredA11y(&m.Metadata, "language", languages[0])
	} else {
		setInferredA11y(&m.Metadata, "language", jsonStrings(languages))
	}

	return &m, nil
}

